import sys
from backend.knowledge_base import SEED_KNOWLEDGE_ARTICLES

sql = []
sql.append('-- ============================================================')
sql.append('-- ASISTIA TEINCO - ESQUEMA Y DATOS INICIALES PARA SUPABASE')
sql.append('-- ============================================================')
sql.append('')
sql.append('DROP TABLE IF EXISTS message_feedbacks CASCADE;')
sql.append('DROP TABLE IF EXISTS chat_messages CASCADE;')
sql.append('DROP TABLE IF EXISTS conversation_sessions CASCADE;')
sql.append('DROP TABLE IF EXISTS knowledge_articles CASCADE;')
sql.append('DROP TABLE IF EXISTS admin_users CASCADE;')
sql.append('')
sql.append('CREATE TABLE admin_users (')
sql.append('    id SERIAL PRIMARY KEY,')
sql.append('    email VARCHAR(100) NOT NULL UNIQUE,')
sql.append('    full_name VARCHAR(150) NOT NULL,')
sql.append('    password_hash VARCHAR(255) NOT NULL,')
sql.append('    role VARCHAR(50) DEFAULT \'Operario\',')
sql.append('    is_active BOOLEAN DEFAULT TRUE,')
sql.append('    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE conversation_sessions (')
sql.append('    id SERIAL PRIMARY KEY,')
sql.append('    session_token VARCHAR(64) NOT NULL UNIQUE,')
sql.append('    user_role VARCHAR(50) DEFAULT \'estudiante\',')
sql.append('    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,')
sql.append('    last_active TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE knowledge_articles (')
sql.append('    id SERIAL PRIMARY KEY,')
sql.append('    division VARCHAR(100) NOT NULL,')
sql.append('    category VARCHAR(100) NOT NULL,')
sql.append('    title VARCHAR(255) NOT NULL,')
sql.append('    content TEXT NOT NULL,')
sql.append('    keywords TEXT,')
sql.append('    contact_email VARCHAR(100),')
sql.append('    contact_phone VARCHAR(100),')
sql.append('    office_location VARCHAR(150),')
sql.append('    schedule VARCHAR(150),')
sql.append('    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,')
sql.append('    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE chat_messages (')
sql.append('    id SERIAL PRIMARY KEY,')
sql.append('    session_id INTEGER NOT NULL REFERENCES conversation_sessions(id) ON DELETE CASCADE,')
sql.append('    sender VARCHAR(20) NOT NULL,')
sql.append('    content TEXT NOT NULL,')
sql.append('    detected_division VARCHAR(100),')
sql.append('    confidence_score FLOAT,')
sql.append('    response_time_ms FLOAT,')
sql.append('    sources_cited TEXT,')
sql.append('    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE message_feedbacks (')
sql.append('    id SERIAL PRIMARY KEY,')
sql.append('    message_id INTEGER NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,')
sql.append('    is_helpful BOOLEAN NOT NULL,')
sql.append('    comment TEXT,')
sql.append('    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP')
sql.append(');')
sql.append('')
sql.append('-- 1. USUARIOS ADMINISTRATIVOS')
sql.append("INSERT INTO admin_users (email, full_name, password_hash, role, is_active) VALUES ('admin@teinco.edu.co', 'Rectoría y Dirección General TEINCO', 'Teinco2026*', 'SuperAdmin', TRUE);")
sql.append("INSERT INTO admin_users (email, full_name, password_hash, role, is_active) VALUES ('coordinador@teinco.edu.co', 'Coordinación de Registro y Control', 'Teinco2026*', 'Operario', TRUE);")
sql.append('')
sql.append('-- 2. ARTICULOS INSTITUCIONALES TEINCO')

def esc(s):
    if not s:
        return "''"
    return "'" + str(s).replace("'", "''") + "'"

for a in SEED_KNOWLEDGE_ARTICLES:
    div = esc(a.get('division', ''))
    cat = esc(a.get('category', ''))
    tit = esc(a.get('title', ''))
    cnt = esc(a.get('content', ''))
    kw = esc(a.get('keywords', ''))
    em = esc(a.get('contact_email', ''))
    ph = esc(a.get('contact_phone', ''))
    loc = esc(a.get('office_location', ''))
    sch = esc(a.get('schedule', ''))
    sql.append(f"INSERT INTO knowledge_articles (division, category, title, content, keywords, contact_email, contact_phone, office_location, schedule) VALUES ({div}, {cat}, {tit}, {cnt}, {kw}, {em}, {ph}, {loc}, {sch});")

with open('supabase_setup.sql', 'w', encoding='utf-8') as f:
    f.write('\n'.join(sql))

print(f'supabase_setup.sql created successfully with {len(SEED_KNOWLEDGE_ARTICLES)} articles!')
